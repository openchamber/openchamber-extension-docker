/** Translate one user-facing string. Unknown text stays English. */
export const t = (text: string): string => {
  if (!text || !isZh()) return text;
  const exact = ZH[text];
  if (exact !== undefined) return exact;
  for (const [pattern, replace] of PATTERNS) {
    const match = pattern.exec(text);
    if (match) return replace(...(match as unknown as string[]));
  }
  return text;
};
